function getExercise(id) {
  return EXERCISES.find(item => item.id === id);
}

function getSport(id) {
  return SPORTS.find(item => item.id === id) || SPORTS[0];
}

function getDirection(sportId, dirId) {
  const sport = getSport(sportId);
  return sport.directions.find(item => item.id === dirId) || sport.directions[0];
}

// Все упражнения, которые встречаются в программах вида занятия
// (вместе с заменами, без повторов)
function sportExerciseIds(sportId) {
  const ids = [];
  getSport(sportId).directions.forEach(d =>
    [...d.warmup, ...d.main.flat(), ...d.cool].forEach(id => { if (!ids.includes(id)) ids.push(id); }));
  return ids;
}

/*
  ЗАМЕНЫ УПРАЖНЕНИЙ (зал). Какие упражнения основной части будут
  в тренировке номер round по этой программе (0 — первая, 1 — вторая…).
  Место-строка не меняется никогда (главное упражнение дня).
  Места-списки меняются по очереди: после каждой тренировки — примерно
  треть из них (1–3 места), каждое переходит к следующей замене в своём
  списке. Через несколько тренировок поменяются все, и круг пойдёт снова.
  Пример: 6 мест с заменами → после 1-й тренировки меняются 1-е и 2-е,
  после 2-й — 3-е и 4-е, после 3-й — 5-е и 6-е, после 4-й — снова 1-е и 2-е.
*/
function mainIds(dir, round = 0) {
  const vars = [];                                   // номера мест с заменами
  dir.main.forEach((slot, j) => { if (Array.isArray(slot) && slot.length > 1) vars.push(j); });
  const perRound = Math.max(1, Math.round(vars.length / 3));   // сколько мест меняется за раз
  const swaps = Math.max(0, round) * perRound;                  // сколько всего было замен
  return dir.main.map((slot, j) => {
    if (!Array.isArray(slot)) return slot;
    const q = vars.indexOf(j);
    if (q < 0) return slot[0];
    // Сколько раз менялось это место (замены идут по кругу мест)
    const times = Math.floor(swaps / vars.length) + (q < swaps % vars.length ? 1 : 0);
    return slot[times % slot.length];
  });
}

/*
  ЦИКЛ ПРОГРАММ (зал). Какая программа следующая после dirId.
  cycleNo — номер цикла, по которому идёте сейчас (программа может быть
  в нескольких циклах, как «Ноги»). Возвращает { dir, cycle } или null,
  если программа не входит ни в один цикл.
*/
function nextInCycle(sport, dirId, cycleNo = 0) {
  const cycles = sport.cycles || [];
  const c = cycles[cycleNo] && cycles[cycleNo].includes(dirId)
    ? cycleNo : cycles.findIndex(cy => cy.includes(dirId));
  if (c < 0) return null;
  const cy = cycles[c];
  return { dir: cy[(cy.indexOf(dirId) + 1) % cy.length], cycle: c };
}
// Цикл, в котором сейчас программа dirId (для подсказки на экране «Направление»)
function cycleOf(sport, dirId, cycleNo = 0) {
  const cycles = sport.cycles || [];
  if (cycles[cycleNo] && cycles[cycleNo].includes(dirId)) return cycles[cycleNo];
  return cycles.find(cy => cy.includes(dirId)) || null;
}

// Как называются подходы у вида занятия: setWord(sport, 3) → «подхода»,
// в беге — «отрезка», в скакалке — «раунда»
function setWord(sport, n) {
  const w = sport.setWords || ['подход', 'подхода', 'подходов'];
  return plural(n, w[0], w[1], w[2]);
}

// Названия групп основной части программы: «Грудь · Трицепс»
function directionGroups(dir) {
  const names = [];
  mainIds(dir).forEach(id => {
    const g = GROUP_NAMES[getExercise(id).group];
    if (g && !names.includes(g)) names.push(g);
  });
  return names;
}

// =====================================================================
//  АВТОПОДБОР ПОД ВРЕМЯ
//
//  Правила:
//  1. Каждое упражнение программы — не больше одного раза.
//  2. Меньше времени → упражнения убираются РАВНОМЕРНО из всех групп
//     мышц (сначала остаётся по одному упражнению на группу,
//     дальше — пропорционально размеру группы).
//  3. Больше времени → сначала добавляются новые упражнения.
//     Когда все уже в плане — каждое делается дольше
//     (в зале — добавляются подходы, до 5).
//  4. Круг на главном экране не даёт выбрать больше, чем программа
//     может заполнить без повторов.
// =====================================================================
const MIN_SCALE = 0.85;       // упражнение можно укоротить до 85%, прежде чем убрать следующее
const MAX_SCALE = 2;          // и удлинить максимум вдвое (если у вида занятия не указан свой maxScale)
const FIXED_MIN_SCALE = 0.5;  // традиционные комплексы (fixed) — укорачиваются до половины
const MAX_SETS = 5;           // в зале — не больше 5 подходов на упражнение
const WARMUP_SHARE = 0.20;    // разминка ≈ 20% времени
const COOL_SHARE = 0.15;      // заминка ≈ 15% времени

// Время одного упражнения со всеми подходами и отдыхом
function itemCost(item, sets) {
  return (item.duration + item.rest) * sets;
}

/*
  Порядок, в котором упражнения ОСТАЮТСЯ при нехватке времени.
  Возвращает номера упражнений: самое важное — первым.
  Сначала — первое упражнение каждой группы (по порядку групп),
  затем остальные — так, чтобы каждая группа сокращалась пропорционально.
*/
function rankByGroups(items) {
  const groups = [];                 // группы в порядке появления
  const members = {};                // группа → номера её упражнений
  items.forEach((item, i) => {
    if (!members[item.group]) { members[item.group] = []; groups.push(item.group); }
    members[item.group].push(i);
  });
  const ranked = items.map((item, i) => {
    const list = members[item.group];
    const pos = list.indexOf(i);
    return {
      i,
      tier: pos === 0 ? 0 : 1,               // первые в группе — вперёд
      share: (pos + 0.5) / list.length,      // доля внутри группы
      g: groups.indexOf(item.group),
    };
  });
  ranked.sort((a, b) => a.tier - b.tier || (a.tier === 0 ? a.g - b.g : a.share - b.share || a.g - b.g));
  return ranked.map(r => r.i);
}

// Растянуть или укоротить упражнение (время кратно 5 секундам, повторы — пропорционально)
function scaleItem(item, scale) {
  if (Math.abs(scale - 1) < 0.01) return;
  const d = Math.max(10, Math.round(item.duration * scale / 5) * 5);
  if (item.type === 'reps') item.reps = Math.max(1, Math.round(item.reps * d / item.duration));
  item.duration = d;
}

/*
  Подобрать одну часть занятия (разминку, основную часть или заминку).
    ids    — список упражнений этой части программы
    budget — сколько секунд на неё отведено
    sets   — подходов на упражнение (1 — без подходов)
    fixed  — true: ничего не выкидывать, только менять длительность
    maxScale — во сколько раз можно удлинить упражнение
    minSets, maxSets — сколько подходов (отрезков) можно оставить и добавить.
             По умолчанию подходы не убираются, а добавляются до 5 (как в зале).
  Возвращает копии упражнений с полем sets.
*/
function planPart(ids, budget, sets = 1, fixed = false, maxScale = MAX_SCALE, minSets = sets, maxSets = MAX_SETS) {
  const items = ids.map(getExercise).filter(Boolean);
  if (items.length === 0 || budget <= 0) return [];

  // 1. Сколько упражнений помещается (в порядке важности)
  let chosen;
  if (fixed) {
    chosen = items.map((_, i) => i);
  } else {
    chosen = [];
    let used = 0;
    for (const i of rankByGroups(items)) {
      const cost = itemCost(items[i], sets);
      if (chosen.length > 0 && (used + cost) * MIN_SCALE > budget) break;
      chosen.push(i);
      used += cost;
    }
    chosen.sort((a, b) => a - b);   // показываем в порядке программы
  }
  const list = chosen.map(i => ({ ...items[i], sets }));
  const allIn = chosen.length === items.length;

  if (sets > 1) {
    let used = list.reduce((s, item) => s + itemCost(item, item.sets), 0);
    const order = rankByGroups(list);
    // 2а. Не помещается — убираем подходы (отрезки), начиная с наименее
    //     важных упражнений, но не меньше minSets. В зале minSets = sets,
    //     поэтому там подходы не убираются.
    let removed = true;
    while (used > budget && removed) {
      removed = false;
      for (const k of order.slice().reverse()) {
        const item = list[k];
        if (used > budget && item.sets > minSets) { item.sets--; used -= item.duration + item.rest; removed = true; }
      }
    }
    // 2б. Если влезли все упражнения — добавляем подходы
    //     (по кругу, начиная с самых важных)
    if (allIn) {
      let added = true;
      while (added) {
        added = false;
        for (const k of order) {
          const item = list[k];
          const oneSet = item.duration + item.rest;
          if (item.sets < maxSets && used + oneSet <= budget) { item.sets++; used += oneSet; added = true; }
        }
      }
    }
  } else {
    // 2б. Остальное: подгоняем длительность упражнений под время
    const work = list.reduce((s, item) => s + item.duration, 0);
    const rest = list.reduce((s, item) => s + item.rest, 0);
    const lo = fixed ? FIXED_MIN_SCALE : MIN_SCALE;
    const hi = allIn ? maxScale : 1.3;   // пока есть невключённые упражнения — растягиваем чуть-чуть
    const scale = Math.min(hi, Math.max(lo, (budget - rest) / work));
    list.forEach(item => scaleItem(item, scale));
  }
  return list;
}

// Самое большое время, которое часть может заполнить без повторов
function partMaxSeconds(ids, sets = 1, maxScale = MAX_SCALE, maxSets = MAX_SETS) {
  return ids.map(getExercise).filter(Boolean).reduce((s, item) =>
    s + (sets > 1 ? itemCost(item, maxSets) : item.duration * maxScale + item.rest), 0);
}

/*
  Границы круга (в минутах) для программы: { min, max, step }.
  max — сколько программа может заполнить без повторов,
  но не больше, чем допускает вид занятия.
*/
function planLimits(sportId, dirId, round = 0) {
  const s = getSport(sportId);
  if (s.simple || dirId === CUSTOM_ID) return { min: s.min, max: s.max, step: s.step };
  const dir = getDirection(sportId, dirId);
  const main = mainIds(dir, round);   // зал: упражнения этой тренировки (с заменами)
  const sets = dir.sets || 1;
  const k = s.maxScale || MAX_SCALE;
  const maxSec = partMaxSeconds(dir.warmup, 1, k) + partMaxSeconds(main, sets, k, dir.maxSets) + partMaxSeconds(dir.cool, 1, k);
  let max = Math.floor(maxSec / 60 / s.step) * s.step;
  max = Math.max(s.min, Math.min(s.max, max));
  let min = s.min;
  // Сколько секунд основной части нужно как минимум
  let needMain = 0;
  if (dir.fixed) {
    // Традиционный комплекс должен поместиться целиком хотя бы на половине длительности
    needMain = main.map(getExercise).reduce((t, item) => t + item.duration * FIXED_MIN_SCALE + item.rest, 0);
  } else if (dir.minSets) {
    // Отрезки (бег, скакалка): самое важное упражнение — хотя бы minSets раз
    const items = main.map(getExercise).filter(Boolean);
    if (items.length) needMain = itemCost(items[rankByGroups(items)[0]], dir.minSets);
  }
  if (needMain) {
    const need = needMain / (1 - (s.warmupShare || WARMUP_SHARE) - (s.coolShare || COOL_SHARE));
    min = Math.max(s.min, Math.ceil(need / 60 / s.step) * s.step);
    min = Math.min(min, max);
  }
  return { min, max, step: s.step };
}

// Разложить подходы по шагам: «Жим лёжа, подход 1 из 4», «…подход 2 из 4»…
function expandSets(list) {
  const result = [];
  list.forEach(item => {
    if (item.sets > 1) {
      for (let s = 1; s <= item.sets; s++) result.push({ ...item, set: s, sets: item.sets });
    } else {
      const copy = { ...item };
      delete copy.sets;
      result.push(copy);
    }
  });
  return result;
}

/*
  Собрать тренировку под нужное время.
    sportId   — вид занятия
    dirId     — программа, или CUSTOM_ID для своей тренировки
    minutes   — желаемая длительность (для своей тренировки не важна)
    customIds — список упражнений своей тренировки
    round     — (зал) номер тренировки по этой программе: от него зависят
                замены упражнений (см. mainIds)
*/
function buildWorkout(sportId, dirId, minutes, customIds = [], round = 0) {
  const s = getSport(sportId);
  const total = minutes * 60;

  // Медитация: один обратный отсчёт на всё время
  if (s.simple) {
    const med = { ...getExercise('meditation'), duration: total };
    return { id: 'meditation_' + minutes, name: s.name, exercises: [med], rounds: 1 };
  }

  // Своя тренировка: каждое выбранное упражнение один раз, в выбранном порядке.
  // Время = сумма упражнений (круг на главном экране показывает его сам).
  if (dirId === CUSTOM_ID) {
    const list = customIds.map(getExercise).filter(Boolean).map(item => {
      // В зале силовые упражнения — подходами; разминки и растяжки — один раз
      const sets = s.sets && item.duration < 120 && item.rest > 0 ? s.sets : 1;
      return { ...item, sets };
    });
    return { id: 'custom_' + sportId, name: 'Своя тренировка', exercises: expandSets(list), rounds: 1 };
  }

  const dir = getDirection(sportId, dirId);
  const main = mainIds(dir, round);   // основная часть этой тренировки (с заменами)
  const sets = dir.sets || 1;

  // Делим время: разминка ~20%, заминка ~15% (у вида занятия могут быть свои доли),
  // остальное — основная часть.
  // Если основная часть «упёрлась» в свой максимум — остаток отдаём разминке и заминке.
  const k = s.maxScale || MAX_SCALE;
  const maxW = partMaxSeconds(dir.warmup, 1, k), maxC = partMaxSeconds(dir.cool, 1, k);
  const maxM = partMaxSeconds(main, sets, k, dir.maxSets);
  const ws = s.warmupShare || WARMUP_SHARE, cs = s.coolShare || COOL_SHARE;
  let w = dir.warmup.length ? Math.min(total * ws, maxW) : 0;
  let c = dir.cool.length ? Math.min(total * cs, maxC) : 0;
  let m = total - w - c;
  if (m > maxM) {
    let extra = m - maxM;
    m = maxM;
    const addW = Math.min(extra, maxW - w); w += addW; extra -= addW;
    c += Math.min(extra, maxC - c);
  }

  const exercises = expandSets([
    ...planPart(dir.warmup, w, 1, false, k),
    ...planPart(main, m, sets, !!dir.fixed, k, dir.minSets || sets, dir.maxSets || MAX_SETS),
    ...planPart(dir.cool, c, 1, false, k),
  ]);
  return { id: 'auto_' + sportId + '_' + dir.id + '_' + minutes, name: dir.name, exercises, rounds: 1 };
}

// Длительность тренировки в секундах (отдых после последнего не считаем)
function workoutDuration(workout) {
  const list = workout.exercises;
  if (list.length === 0) return 0;
  const sum = list.reduce((s, item) => s + item.duration + item.rest, 0);
  return sum - list[list.length - 1].rest;
}

// Красиво показать время: 95 → «1 мин 35 с», 40 → «40 с».
function formatDuration(seconds) {
  seconds = Math.round(seconds);
  const min = Math.floor(seconds / 60);
  const sec = seconds % 60;
  if (min === 0) return sec + ' с';
  if (sec === 0) return min + ' мин';
  return min + ' мин ' + sec + ' с';
}

// Часы «м:сс»: 75 → «1:15»
function formatClock(seconds) {
  const s = Math.max(0, Math.ceil(seconds));
  return Math.floor(s / 60) + ':' + String(s % 60).padStart(2, '0');
}

// Склонение: plural(3, 'упражнение', 'упражнения', 'упражнений')
function plural(n, one, few, many) {
  const n10 = n % 10, n100 = n % 100;
  if (n10 === 1 && n100 !== 11) return one;
  if (n10 >= 2 && n10 <= 4 && (n100 < 10 || n100 >= 20)) return few;
  return many;
}
