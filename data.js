/*
  УПРАЖНЕНИЕ — поля:
    id          — уникальный код (латиницей, без пробелов)
    group       — группа мышц или раздел (см. GROUP_NAMES ниже).
                  По группам приложение РАВНОМЕРНО сокращает программу,
                  когда времени мало.
    name        — название, которое видит пользователь
    description — коротко: как выполнять
    duration    — сколько секунд длится упражнение (или один подход)
    rest        — сколько секунд отдыха ПОСЛЕ упражнения (подхода)
    type        — 'time' — делаем, пока идёт таймер;
                  'reps' — делаем указанное число повторов
    reps        — число повторов (только для type: 'reps', иначе null)
    anim        — какая анимация фигурки показывается (см. index.html)
    tips        — подсказки: техника, дыхание, ощущения.
                  Идут бегущей строкой; по нажатию — показываются целиком.
    video_url   — ссылка на видео (позже; если заполнить — покажется вместо анимации)
    voice_text  — текст для голосовой подсказки (позже, пока пусто)

  Помощник ex(...) просто собирает объект, чтобы строки были короче.
  Если указано reps — тип упражнения становится 'reps'.
*/
function ex(id, group, name, description, duration, rest, anim, tips, reps = null) {
  return {
    id, group, name, description, duration, rest,
    type: reps ? 'reps' : 'time', reps,
    anim: anim || 'idle',
    tips: tips || [],
    video_url: '', voice_text: '',
  };
}

