// По умолчанию: зарядка, общий комплекс
const DEFAULT_SPORT = 'morning';

// Код «своей тренировки» (выбирается вместо программы)
const CUSTOM_ID = 'custom';

// ---------------------------------------------------------------------
//  Функции-помощники
// ---------------------------------------------------------------------

function getExercise(id) {
  return EXERCISES.find(item => item.id === id);
}

function getSport(id) {
  return SPORTS.find(item => item.id === id) || SPORTS[0];
}

function getDirection(sportId, dirId) {
  const sport = getSport(sportId);
  return sport.directions.find(item => item.id === dirId) || sport.directions[0];
}

// Все упражнения, которые встречаются в программах вида занятия (без повторов)
function sportExerciseIds(sportId) {
  const ids = [];
  getSport(sportId).directions.forEach(d =>
    [...d.warmup, ...d.main, ...d.cool].forEach(id => { if (!ids.includes(id)) ids.push(id); }));
  return ids;
}

/*
  Набрать упражнения из списка ids на заданное число секунд (budget).
  Идём по списку по кругу и добавляем, пока укладываемся.
  sets > 1 — каждое упражнение добавляется подходами подряд (зал).
  Если без подходов одно и то же упражнение выпадает дважды подряд,
  просто удлиняем его.
*/
function fillPart(ids, budget, sets = 1) {
  const pool = ids.map(getExercise).filter(Boolean);
  const result = [];
  if (pool.length === 0 || budget <= 0) return result;

  let used = 0;
  let i = 0;
  while (true) {
    const base = pool[i % pool.length];
    const cost = (base.duration + base.rest) * sets;
    // Добавляем, если после этого перебор не больше половины.
    // Самое первое добавляем всегда.
    if (result.length > 0 && used + cost > budget + cost / 2) break;

    const last = result[result.length - 1];
    if (sets > 1) {
      for (let s = 1; s <= sets; s++) result.push({ ...base, set: s, sets });
      used += cost;
    } else if (last && last.id === base.id) {
      // Удлиняем предыдущее (повторы тоже увеличиваем)
      last.duration += base.duration;
      if (last.type === 'reps') last.reps += base.reps;
      used += base.duration;
    } else {
      result.push({ ...base }); // копия, чтобы не портить библиотеку
      used += cost;
    }
    i++;
    if (i > 500) break; // защита от бесконечного цикла
  }
  return result;
}

/*
  Собрать тренировку под нужное время.
    sportId   — вид занятия
    dirId     — программа, или CUSTOM_ID для своей тренировки
    minutes   — желаемая длительность
    customIds — список упражнений своей тренировки
  Время: разминка ~20%, заминка ~15%, остальное — основная часть.
*/
function buildWorkout(sportId, dirId, minutes, customIds = []) {
  const total = minutes * 60;
  let dir;
  if (dirId === CUSTOM_ID) {
    dir = { id: CUSTOM_ID, name: 'Своя тренировка', warmup: [], main: customIds, cool: [],
            sets: getSport(sportId).id === 'gym' ? 3 : 1 };
  } else {
    dir = getDirection(sportId, dirId);
  }

  let warmupBudget = dir.warmup.length ? Math.round(total * 0.20) : 0;
  let coolBudget   = dir.cool.length   ? Math.round(total * 0.15) : 0;
  let mainBudget   = total - warmupBudget - coolBudget;
  if (dir.main.length === 0) { warmupBudget += mainBudget; mainBudget = 0; }

  const exercises = [
    ...fillPart(dir.warmup, warmupBudget),
    ...fillPart(dir.main,   mainBudget, dir.sets || 1),
    ...fillPart(dir.cool,   coolBudget),
  ];

  return { id: 'auto_' + sportId + '_' + dir.id + '_' + minutes, name: dir.name, exercises, rounds: 1 };
}

// Длительность тренировки в секундах (отдых после последнего не считаем)
function workoutDuration(workout) {
  const list = workout.exercises;
  if (list.length === 0) return 0;
  const sum = list.reduce((s, item) => s + item.duration + item.rest, 0);
  return sum - list[list.length - 1].rest;
}

// Красиво показать время: 95 → «1 мин 35 с», 40 → «40 с».
function formatDuration(seconds) {
  seconds = Math.round(seconds);
  const min = Math.floor(seconds / 60);
  const sec = seconds % 60;
  if (min === 0) return sec + ' с';
  if (sec === 0) return min + ' мин';
  return min + ' мин ' + sec + ' с';
}

// Часы «м:сс»: 75 → «1:15»
function formatClock(seconds) {
  const s = Math.max(0, Math.ceil(seconds));
  return Math.floor(s / 60) + ':' + String(s % 60).padStart(2, '0');
}

// Склонение: plural(3, 'упражнение', 'упражнения', 'упражнений')
function plural(n, one, few, many) {
  const n10 = n % 10, n100 = n % 100;
  if (n10 === 1 && n100 !== 11) return one;
  if (n10 >= 2 && n10 <= 4 && (n100 < 10 || n100 >= 20)) return few;
  return many;
}
